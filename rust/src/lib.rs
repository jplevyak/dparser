//! A native Rust runtime for DParser grammars.
//!
//! Grammars are compiled by `make_dparser -B` into binary tables, and their
//! actions (written in Rust) are turned into a dispatch function by
//! [`build_actions`].  See the crate README and the DParser documentation.

pub mod attrs;
pub mod binary_format;
pub mod builder;

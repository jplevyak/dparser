use grammar::*;
use std::collections::HashMap;
use std::rc::Rc;

/// The kind of action being dispatched.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ActionKind {
    /// `[ ... ]`: run when the rule is reduced, possibly for a parse that is
    /// later abandoned.  Returning nonzero (`${reject}`) rejects the parse path.
    Speculative,
    /// `{ ... }`: run on the final parse tree.
    Final,
    /// Code for the pass with this index (`${pass ...}`), run by [`Parser::pass`].
    Pass(u32),
}

/// The action dispatcher generated by [`build_actions`].
///
/// It returns `None` if the rule has no action of `kind`.  With `probe` set
/// it only reports whether the action exists, without running it.  `ps` is
/// the node (`$n`); its children are the rule's elements (`$n0`, `$n1`, ...).
pub type DispatchActionFn<G, N> = fn(
    kind: ActionKind,
    action_index: i32,
    probe: bool,
    ps: &mut ParseNode<'_, N>,
    globals: Option<&mut G>,
    parser: &mut Parser<G, N>,
) -> Option<i32>;

/// A whitespace function: skip whitespace in `input` from `loc`, updating
/// `loc.s`, `loc.line` and `loc.col`.
pub type WhiteSpaceFn<G> = fn(input: &[u8], loc: &mut Loc, globals: Option<&mut G>);

/// A whitespace function that also reads the threaded state: the state after
/// the preceding token.  It cannot change the state.
pub type WhiteSpaceStateFn<G> =
    fn(input: &[u8], loc: &mut Loc, globals: Option<&mut G>, states: &States, state: StateId);

/// Chooses between parses that end with different threaded states: >0
/// prefers `a`, <0 prefers `b`, 0 neither.
pub type PreferStateFn = fn(states: &States, a: StateId, b: StateId) -> i32;

/// A function choosing among ambiguous parses; returns the index of the
/// alternative to keep.  The alternatives' final actions have not run yet.
pub type AmbiguityFn<G, N> = fn(&mut Parser<G, N>, usize, &mut [ParseNode<'_, N>]) -> usize;

/// The external scanners of a grammar (`${scan ...}` and `${scanner ...}`),
/// generated by [`build_actions`] as `dispatch_scan`.  Scans `input` at `loc`
/// in parser state `state`; on a match, advances `loc`, sets the outputs and
/// returns nonzero.
pub type ScanFn = fn(
    state: usize,
    input: &[u8],
    loc: &mut Loc,
    symbol: &mut u16,
    term_priority: &mut i32,
    op_assoc: &mut u8,
    op_priority: &mut i32,
) -> i32;

/// Everything [`build_actions`] generates for a grammar, returned by the
/// generated `actions()` function.
pub struct Actions<G: 'static, N: 'static> {
    pub dispatch: Option<DispatchActionFn<G, N>>,
    pub scan: Option<ScanFn>,
    pub white_space: Option<WhiteSpaceFn<G>>,
}

/// A node of the engine, for speculative actions.
pub(crate) struct SpecNode<N> {
    pub symbol: i32,
    pub start: Loc,
    pub end: usize,
    pub end_skip: usize,
    pub user: N,
    pub scope: ScopeId,
    pub state: StateId,
    pub state_before: StateId,
    pub action_index: i32,
    pub error_recovery: bool,
}

/// Access to the engine's nodes while a speculative action runs.
pub(crate) struct SpecAccess<N> {
    pub engine: *mut (),
    pub find: fn(*const (), u32, i32) -> Option<u32>,
    pub children: fn(*const (), u32) -> Vec<u32>,
    pub node: fn(*const (), u32) -> SpecNode<N>,
    /// cmp_greediness and height, for resolve_amb_greedy.
    pub greedy: fn(*mut (), u32, u32) -> i32,
    pub height: fn(*const (), u32) -> u32,
}

/// An [`AmbiguityFn`] that prefers the greedier parse, then the shallower
/// one (`resolve_amb_greedy` in C).
pub fn resolve_amb_greedy<G: 'static, N: 'static + Default + Clone>(
    p: &mut Parser<G, N>,
    n: usize,
    v: &mut [ParseNode<'_, N>],
) -> usize {
    let Some(spec) = &p.spec else { return 0 };
    let mut selected = 0;
    for i in 1..n.min(v.len()) {
        let (x, y) = (v[i].node, v[selected].node);
        if x == u32::MAX || y == u32::MAX {
            continue;
        }
        let r = (spec.greedy)(spec.engine, x, y);
        if r < 0 || (r == 0 && (spec.height)(spec.engine, x) < (spec.height)(spec.engine, y)) {
            selected = i;
        }
    }
    selected
}

pub struct Parser<G: 'static, N: 'static> {
    globals: Option<*mut G>,
    pub(crate) spec: Option<SpecAccess<N>>,
    tables: Rc<SafeGrammarTables>,
    dispatch_action: Option<DispatchActionFn<G, N>>,
    scan_fn: Option<ScanFn>,
    action_presence: HashMap<(ActionKind, i32), bool>,

    /// Called on a syntax error, with `loc` set; by default the error is
    /// reported on stderr as `pathname:line: syntax error after '...'`.
    pub syntax_error_fn: Option<fn(&mut Self)>,
    /// Chooses among ambiguous parses.  Without one, an unresolved ambiguity is
    /// reported on stderr and the parse fails.
    pub ambiguity_fn: Option<AmbiguityFn<G, N>>,
    /// Replaces the default whitespace handling (or the grammar's whitespace
    /// production).
    pub white_space_fn: Option<WhiteSpaceFn<G>>,
    /// Like `white_space_fn`, but also given the threaded state; used
    /// instead of it when set.
    pub white_space_state_fn: Option<WhiteSpaceStateFn<G>>,
    /// Keep the parse tree.  Without it, final actions still run, but nodes
    /// don't keep their children once their actions have run.  Defaults to
    /// on if the grammar has `${declare save_parse_tree}`.
    pub save_parse_tree: bool,
    /// The parser state to start in; see [`set_start_symbol`](Self::set_start_symbol).
    pub start_state: usize,
    /// Accept a parse of a prefix of the input.
    pub partial_parses: bool,
    /// Don't flatten the internal nodes created for `*`, `+` and groups.
    pub dont_fixup_internal_productions: bool,
    /// Also splice EBNF nodes into their parents.
    pub fixup_ebnf_productions: bool,
    pub dont_compare_stacks: bool,
    pub dont_merge_epsilon_trees: bool,
    pub dont_use_greediness_for_disambiguation: bool,
    pub dont_use_height_for_disambiguation: bool,
    pub dont_use_deep_priorities_for_disambiguation: bool,
    /// Run final actions once the parse has been unambiguous for this many
    /// shifts, rather than all at the end.
    pub commit_actions_interval: u32,
    /// Try to recover from syntax errors using the grammar's error recovery
    /// hints.
    pub error_recovery: bool,
    /// The file name used in error messages.
    pub pathname: String,
    /// The line of the start of the input.
    pub start_line: u32,
    /// After a parse, the location of the last syntax error (or the start).
    pub loc: Loc,
    /// The number of syntax errors in the last parse.
    pub syntax_errors: u32,
    /// The symbol table.  A new one is made for each parse unless
    /// `initial_scope` is set.
    pub symtab: SymTab,
    /// The scope to start parsing in, in `symtab`.
    pub initial_scope: Option<ScopeId>,
    /// The threaded state values, which live as long as the parser.
    pub states: States,
    /// The threaded state at the start of a parse (see [`make_state`](Self::make_state)).
    pub initial_state: StateId,
    /// Chooses between parses that end with different threaded states,
    /// before `ambiguity_fn` sees them.
    pub prefer_state: Option<PreferStateFn>,
    /// Counts from the last parse.
    pub stats: Stats,
}

impl<G: 'static, N: 'static + Default + Clone> Parser<G, N> {
    /// A parser for `tables_bytes` (from `make_dparser -B`) with the action
    /// dispatcher generated by [`build_actions`].  For grammars with external
    /// scanners or a whitespace function, use [`with_actions`](Self::with_actions).
    pub fn new(tables_bytes: &[u8], dispatch_action: Option<DispatchActionFn<G, N>>) -> Result<Self, &'static str> {
        Self::with_actions(tables_bytes, Actions { dispatch: dispatch_action, scan: None, white_space: None })
    }

    /// A parser for `tables_bytes` with everything [`build_actions`] generated:
    /// `Parser::with_actions(tables, actions())`.
    pub fn with_actions(tables_bytes: &[u8], actions: Actions<G, N>) -> Result<Self, &'static str> {
        let tables = tables::BinaryTables::from_bytes(tables_bytes)?;
        if actions.scan.is_none() && tables.states.iter().any(|s| s.has_scanner_code) {
            return Err("The grammar has external scanners: use Parser::with_actions(tables, actions())");
        }
        if actions.white_space.is_none() && tables.has_default_white_space {
            return Err("The grammar declares a whitespace function: use Parser::with_actions(tables, actions())");
        }
        Ok(Parser {
            globals: None,
            spec: None,
            save_parse_tree: tables.save_parse_tree,
            tables: Rc::new(tables),
            dispatch_action: actions.dispatch,
            scan_fn: actions.scan,
            action_presence: HashMap::new(),
            syntax_error_fn: None,
            ambiguity_fn: None,
            white_space_fn: actions.white_space,
            white_space_state_fn: None,
            start_state: 0,
            partial_parses: false,
            dont_fixup_internal_productions: false,
            fixup_ebnf_productions: false,
            dont_compare_stacks: false,
            dont_merge_epsilon_trees: false,
            dont_use_greediness_for_disambiguation: false,
            dont_use_height_for_disambiguation: false,
            dont_use_deep_priorities_for_disambiguation: false,
            commit_actions_interval: 100,
            error_recovery: true,
            pathname: String::new(),
            start_line: 1,
            loc: Loc { s: 0, ws: 0, line: 1, col: 0 },
            syntax_errors: 0,
            symtab: SymTab::new(),
            initial_scope: None,
            states: States::new(),
            initial_state: StateId::NONE,
            prefer_state: None,
            stats: Stats::default(),
        })
    }

    /// A threaded state value, for `${state}` or `initial_state`:
    /// `${state} = ${parser}.make_state(depth + 1);`
    pub fn make_state<T: std::any::Any + Eq + std::hash::Hash>(&mut self, value: T) -> StateId {
        self.states.intern(value)
    }

    /// The value of a threaded state, if it is a `T`:
    /// `let depth = ${parser}.state::<i32>(${state}).copied().unwrap_or(0);`
    pub fn state<T: std::any::Any>(&self, id: StateId) -> Option<&T> {
        self.states.get(id)
    }

    /// The parse tables.
    pub fn tables(&self) -> &SafeGrammarTables {
        &self.tables
    }

    /// Start parsing at nonterminal `name`, which must have a start state
    /// (`${declare subparser name}`, or `make_dparser -A`).
    pub fn set_start_symbol(&mut self, name: &str) -> Result<(), String> {
        let state = self
            .tables
            .symbols
            .iter()
            .find(|s| s.kind == D_SYMBOL_NTERM && s.name == name)
            .map(|s| s.start_symbol)
            .ok_or_else(|| format!("unknown nonterminal '{}'", name))?;
        if state < 0 {
            return Err(format!("'{}' has no start state; declare it with ${{declare subparser {}}}", name, name));
        }
        self.start_state = state as usize;
        Ok(())
    }

    pub fn set_save_parse_tree(&mut self, b: bool) {
        self.save_parse_tree = b;
    }

    /// Set the file name and starting line used for locations and errors.
    pub fn set_loc(&mut self, pathname: &str, line: u32) {
        self.pathname = pathname.to_string();
        self.start_line = line;
    }

    /// The first node in the tree under `node` (including `node`) with
    /// `symbol`, depth first (`d_find_in_tree`).  In speculative actions this
    /// searches the whole derivation, not just the children given to the action.
    pub fn find_in_tree<'a>(&self, node: &ParseNode<'a, N>, symbol: i32) -> Option<ParseNode<'a, N>> {
        match &self.spec {
            Some(spec) if node.node != u32::MAX => {
                let found = (spec.find)(spec.engine as *const (), node.node, symbol)?;
                Some(self.spec_view(node, found))
            }
            _ => {
                if node.symbol == symbol {
                    return Some(node.clone());
                }
                node.children.iter().find_map(|c| self.find_in_tree(c, symbol))
            }
        }
    }

    /// The children of `node` (`d_get_child`).  In speculative actions this
    /// works for any node of the derivation, not just the action's children.
    pub fn children<'a>(&self, node: &ParseNode<'a, N>) -> Vec<ParseNode<'a, N>> {
        match &self.spec {
            Some(spec) if node.node != u32::MAX => {
                (spec.children)(spec.engine as *const (), node.node).into_iter().map(|c| self.spec_view(node, c)).collect()
            }
            _ => node.children.clone(),
        }
    }

    /// A view of engine node `id`, which lies within `within`.
    fn spec_view<'a>(&self, within: &ParseNode<'a, N>, id: u32) -> ParseNode<'a, N> {
        let spec = self.spec.as_ref().unwrap();
        let n = (spec.node)(spec.engine as *const (), id);
        ParseNode {
            symbol: n.symbol,
            string: within.sub_str(n.start.s, n.end),
            end_skip_string: within.sub_str(n.end, n.end_skip),
            start_loc: n.start,
            end: n.end,
            children: Vec::new(),
            user: n.user,
            scope: n.scope,
            state: n.state,
            state_before: n.state_before,
            action_index: n.action_index,
            error_recovery: n.error_recovery,
            node: id,
        }
    }

    /// The number of a pass, by name.
    pub fn pass_number(&self, name: &str) -> Option<usize> {
        self.tables.passes.iter().position(|p| p.name == name)
    }

    /// Parse `input`.  Returns the root of the parse tree, or `None` if the
    /// input could not be parsed (see `syntax_errors` and `loc`).  If error
    /// recovery succeeded, a tree is returned and `syntax_errors` is nonzero.
    pub fn parse<'a>(&mut self, input: &'a str, globals: Option<&mut G>) -> Option<ParseNode<'a, N>> {
        // Input used to require a trailing '\0'.  Trailing NULs are ignored.
        let bytes = input.as_bytes();
        let mut end = bytes.len();
        while end > 0 && bytes[end - 1] == 0 {
            end -= 1;
        }
        self.globals = globals.map(|g| g as *mut G);
        self.syntax_errors = 0;
        self.loc = Loc { s: 0, ws: 0, line: self.start_line, col: 0 };
        let top = match self.initial_scope {
            Some(s) => s,
            None => {
                self.symtab = SymTab::new();
                let t = self.symtab.new_scope(None);
                self.symtab.set_kind(t, symtab::D_SCOPE_SEQUENTIAL);
                t
            }
        };
        let ws_mode = if self.white_space_fn.is_some() || self.white_space_state_fn.is_some() {
            engine::WsMode::User
        } else if self.tables.whitespace_state != 0 {
            engine::WsMode::Subparser
        } else {
            engine::WsMode::Builtin
        };
        let result = if self.start_state < self.tables.states.len() {
            let mut engine = engine::Engine::new(self.tables.clone(), input, end, ws_mode, top);
            engine.top_state = self.initial_state;
            engine.loc = self.loc;
            engine.set_partial_parses(self.partial_parses);
            engine.set_error_recovery(self.error_recovery);
            let r = engine.exhaustive_parse(self, self.start_state);
            self.loc = engine.loc;
            let tree = if r == 0 { engine.root(self).and_then(|root| engine.commit_tree(self, root)) } else { None };
            self.stats = engine.stats;
            tree
        } else {
            None
        };
        self.globals = None;
        result
    }

    /// Run pass `pass_number` (see [`pass_number`](Self::pass_number)) over
    /// the tree under `node`, as `d_pass` in C.  Its actions get no globals;
    /// see [`pass_with_globals`](Self::pass_with_globals).
    pub fn pass(&mut self, node: &mut ParseNode<'_, N>, pass_number: usize) {
        let Some(pp) = self.tables.passes.get(pass_number).cloned() else {
            panic!("bad pass number: {}", pass_number)
        };
        if pp.kind & D_PASS_MANUAL != 0 {
            self.pass_call(&pp, node);
        } else if pp.kind & D_PASS_PRE_ORDER != 0 {
            self.pass_preorder(&pp, node);
        } else if pp.kind & D_PASS_POST_ORDER != 0 {
            self.pass_postorder(&pp, node);
        }
    }

    /// Run pass `pass_number` with `globals` available to its actions (as
    /// `$g`).  From an action, use `${parser}.pass_with_globals($n, n, $g)`.
    pub fn pass_with_globals(&mut self, node: &mut ParseNode<'_, N>, pass_number: usize, globals: &mut G) {
        let saved = self.globals.replace(globals as *mut G);
        self.pass(node, pass_number);
        self.globals = saved;
    }

    fn pass_found(&mut self, pp: &GrammarPass, node: &ParseNode<'_, N>) -> bool {
        self.has_action(ActionKind::Pass(pp.index), node.action_index)
    }

    fn pass_call(&mut self, pp: &GrammarPass, node: &mut ParseNode<'_, N>) {
        if self.pass_found(pp, node) {
            let idx = node.action_index;
            self.call_action(ActionKind::Pass(pp.index), idx, node);
        }
    }

    fn pass_recurse(&self, pp: &GrammarPass, found: bool) -> bool {
        pp.kind & D_PASS_FOR_ALL != 0 || (pp.kind & D_PASS_FOR_UNDEFINED != 0 && !found)
    }

    fn pass_preorder(&mut self, pp: &GrammarPass, node: &mut ParseNode<'_, N>) {
        let found = self.pass_found(pp, node);
        self.pass_call(pp, node);
        if self.pass_recurse(pp, found) {
            for c in node.children.iter_mut() {
                self.pass_preorder(pp, c);
            }
        }
    }

    fn pass_postorder(&mut self, pp: &GrammarPass, node: &mut ParseNode<'_, N>) {
        let found = self.pass_found(pp, node);
        if self.pass_recurse(pp, found) {
            for c in node.children.iter_mut() {
                self.pass_postorder(pp, c);
            }
        }
        self.pass_call(pp, node);
    }

    pub(crate) fn scan_fn(&self) -> Option<ScanFn> {
        self.scan_fn
    }

    pub(crate) fn globals_mut(&mut self) -> Option<&mut G> {
        self.globals.map(|g| unsafe { &mut *g })
    }

    /// Whether the grammar has an action of `kind` for `action_index`.
    pub(crate) fn has_action(&mut self, kind: ActionKind, action_index: i32) -> bool {
        if action_index == i32::MIN {
            return false;
        }
        if let Some(&b) = self.action_presence.get(&(kind, action_index)) {
            return b;
        }
        let Some(f) = self.dispatch_action else { return false };
        let mut dummy = ParseNode {
            symbol: 0,
            string: "",
            end_skip_string: "",
            start_loc: Loc::default(),
            end: 0,
            children: Vec::new(),
            user: N::default(),
            scope: ScopeId(0),
            state: StateId::NONE,
            state_before: StateId::NONE,
            action_index,
            error_recovery: false,
            node: u32::MAX,
        };
        let b = f(kind, action_index, true, &mut dummy, None, self).is_some();
        self.action_presence.insert((kind, action_index), b);
        b
    }

    pub(crate) fn call_action(
        &mut self,
        kind: ActionKind,
        action_index: i32,
        ps: &mut ParseNode<'_, N>,
    ) -> i32 {
        let Some(f) = self.dispatch_action else { return 0 };
        // The action gets the only reference to the globals while it runs;
        // nested calls (e.g. pass_with_globals) must be given them explicitly.
        let g = self.globals.take();
        let r = f(kind, action_index, false, ps, g.map(|g| unsafe { &mut *g }), self);
        self.globals = g;
        r.unwrap_or(0)
    }
}
